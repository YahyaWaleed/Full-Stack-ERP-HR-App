/* ---- 9.9 audit trail ---------------------------------------------------- */
CREATE TABLE audit_log (
  audit_id     BIGINT AUTO_INCREMENT PRIMARY KEY,
  occurred_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actor        VARCHAR(50) NOT NULL,
  action       VARCHAR(40) NOT NULL,
  target_type  VARCHAR(40) NOT NULL,
  target_id    VARCHAR(40) NOT NULL,
  details      VARCHAR(500),
  INDEX idx_audit_target (target_type, target_id),
  INDEX idx_audit_time (occurred_at)
) ENGINE=InnoDB;

/* ---- 9.5 refresh tokens + disabling users -------------------------------- */
ALTER TABLE hr_users ADD COLUMN enabled TINYINT(1) NOT NULL DEFAULT 1;

CREATE TABLE refresh_tokens (
  token_id    BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id     INT NOT NULL,
  token_hash  CHAR(64) NOT NULL UNIQUE,      -- SHA-256 of the cookie value; the raw token is never stored
  expires_at  DATETIME NOT NULL,
  revoked_at  DATETIME NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES hr_users(user_id) ON DELETE CASCADE,
  INDEX idx_refresh_user (user_id)
) ENGINE=InnoDB;

/* ---- performance: headcount view joined to active contracts ---------------
   Replaces one fn_current_basic() lookup per employee inside AVG(). */
CREATE OR REPLACE VIEW v_headcount_by_dept AS
SELECT d.code, d.name_ar AS department, b.name_ar AS branch,
       COUNT(e.emp_id) AS headcount,
       SUM(e.gender = 'M') AS males, SUM(e.gender = 'F') AS females,
       ROUND(AVG(TIMESTAMPDIFF(YEAR, e.hire_date, CURDATE())),1) AS avg_service_years,
       ROUND(AVG(IFNULL(c.basic_salary, 0)),2) AS avg_basic_salary
FROM departments d
JOIN branches b ON b.branch_id = d.branch_id
LEFT JOIN employees e ON e.dept_id = d.dept_id AND e.emp_status IN ('ACTIVE','PROBATION')
LEFT JOIN (SELECT emp_id, basic_salary,
                  ROW_NUMBER() OVER (PARTITION BY emp_id ORDER BY start_date DESC) AS rn
             FROM employee_contracts
            WHERE status = 'ACTIVE' AND start_date <= CURDATE()
              AND (end_date IS NULL OR end_date >= CURDATE())) c
       ON c.emp_id = e.emp_id AND c.rn = 1
GROUP BY d.code, d.name_ar, b.name_ar;
