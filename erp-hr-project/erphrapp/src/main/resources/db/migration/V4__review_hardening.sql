/* ---- 5.5 employee codes: EMP-0001, EMP-0002, ... handed out by the database -
   A counter row locked inside the trigger keeps concurrent inserts from ever
   getting the same code. */
CREATE TABLE code_sequences (
  name       VARCHAR(20) PRIMARY KEY,
  next_value INT NOT NULL
) ENGINE=InnoDB;

INSERT INTO code_sequences (name, next_value)
SELECT 'EMP', COALESCE(MAX(emp_id), 0) + 1 FROM employees;

DELIMITER $$
CREATE TRIGGER trg_employees_code
BEFORE INSERT ON employees
FOR EACH ROW
BEGIN
  DECLARE v_next INT;
  IF NEW.emp_code IS NULL OR NEW.emp_code = '' THEN
    SELECT next_value INTO v_next FROM code_sequences WHERE name = 'EMP' FOR UPDATE;
    UPDATE code_sequences SET next_value = v_next + 1 WHERE name = 'EMP';
    SET NEW.emp_code = CONCAT('EMP-', LPAD(v_next, 4, '0'));
  END IF;
END$$
DELIMITER ;

